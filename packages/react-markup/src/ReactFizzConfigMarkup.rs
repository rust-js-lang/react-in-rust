pub fn push_start_instance(
    target: &Chunks,
    r#type: &str,
    props: &'static Unknown,
    resumable_state: &ResumableState,
    render_state: &RenderState,
    preamble_state: Option<&PreambleState>,
    hoistable_state: Option<&HoistableState>,
    format_context: &FormatContext,
    text_embedded: bool,
) -> Option<&'static ReactNodeList> {
    for prop_key in js::keys_in(props) {
        if HAS_OWN_PROPERTY.with(|has_own_property| has_own_property.call(props, &prop_key)) {
            let prop_value = js::get(props, &prop_key);
            if prop_key == "ref" && prop_value.is_some() {
                panic!("Cannot pass ref in renderToHTML because they will never be hydrated.");
            }
            if matches!(js::classify(prop_value), Kind::Function(_)) {
                panic!(
                    "Cannot pass event handlers ({prop_key}) in renderToHTML because the HTML will never be hydrated so they can never get called."
                );
            }
        }
    }

    push_start_instance_impl(
        target,
        r#type,
        props,
        resumable_state,
        render_state,
        preamble_state,
        hoistable_state,
        format_context,
        text_embedded,
    )
}

pub fn push_text_instance(
    target: &Chunks,
    text: &str,
    _render_state: &RenderState,
    _text_embedded: bool,
) -> bool {
    // Markup doesn't need any termination.
    target
        .borrow_mut()
        .push(string_to_chunk(&escape_text_for_browser(Some(
            js::unknown(text),
        ))));
    false
}

