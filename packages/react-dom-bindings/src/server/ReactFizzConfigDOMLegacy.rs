pub struct RenderState {
    // Keep this in sync with ReactFizzConfigDOM
    #[cfg_attr(rust_js, rust_js::flatten)]
    pub base: BaseRenderState,
    // This is an extra field for the legacy renderer
    pub generate_static_markup: bool,
}

unsafe impl js::Defined for RenderState {}

pub fn create_render_state(
    resumable_state: &ResumableState,
    generate_static_markup: bool,
) -> RenderState {
    let render_state = create_render_state_impl(resumable_state, None, None, None, None, None);
    RenderState {
        // Keep this in sync with ReactFizzConfigDOM
        base: render_state,

        // This is an extra field for the legacy renderer
        generate_static_markup,
    }
}

