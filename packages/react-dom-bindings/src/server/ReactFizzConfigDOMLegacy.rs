pub fn push_text_instance(
    target: &Chunks,
    text: &str,
    render_state: &RenderState,
    text_embedded: bool,
) -> bool {
    if render_state.generate_static_markup {
        target
            .borrow_mut()
            .push(string_to_chunk(&escape_text_for_browser(Some(
                js::unknown(text),
            ))));
        false
    } else {
        push_text_instance_impl(target, text, &render_state.base, text_embedded)
    }
}

pub fn push_segment_finale(
    target: &Chunks,
    render_state: &RenderState,
    last_pushed_text: bool,
    text_embedded: bool,
) {
    if render_state.generate_static_markup {
        return;
    }
    push_segment_finale_impl(target, &render_state.base, last_pushed_text, text_embedded);
}

pub fn push_start_activity_boundary(target: &Chunks, render_state: &RenderState) {
    if render_state.generate_static_markup {
        // A completed boundary is done and doesn't need a representation in the HTML
        // if we're not going to be hydrating it.
        return;
    }
    push_start_activity_boundary_impl(target, &render_state.base);
}

pub fn push_end_activity_boundary(target: &Chunks, render_state: &RenderState) {
    if render_state.generate_static_markup {
        return;
    }
    push_end_activity_boundary_impl(target, &render_state.base);
}

pub fn write_start_completed_suspense_boundary(
    destination: &Destination,
    render_state: &RenderState,
) -> bool {
    if render_state.generate_static_markup {
        // A completed boundary is done and doesn't need a representation in the HTML
        // if we're not going to be hydrating it.
        return true;
    }
    write_start_completed_suspense_boundary_impl(destination, &render_state.base)
}

pub fn write_start_client_rendered_suspense_boundary(
    destination: &Destination,
    render_state: &RenderState,
    // flushing these error arguments are not currently supported in this legacy streaming format.
    error_digest: Option<&str>,
    error_message: Option<&str>,
    error_stack: Option<&str>,
    error_component_stack: Option<&str>,
) -> bool {
    if render_state.generate_static_markup {
        // A client rendered boundary is done and doesn't need a representation in the HTML
        // since we'll never hydrate it. This is arguably an error in static generation.
        return true;
    }
    write_start_client_rendered_suspense_boundary_impl(
        destination,
        &render_state.base,
        error_digest,
        error_message,
        error_stack,
        error_component_stack,
    )
}

pub fn write_end_completed_suspense_boundary(
    destination: &Destination,
    render_state: &RenderState,
) -> bool {
    if render_state.generate_static_markup {
        return true;
    }
    write_end_completed_suspense_boundary_impl(destination, &render_state.base)
}

pub fn write_end_client_rendered_suspense_boundary(
    destination: &Destination,
    render_state: &RenderState,
) -> bool {
    if render_state.generate_static_markup {
        return true;
    }
    write_end_client_rendered_suspense_boundary_impl(destination, &render_state.base)
}

