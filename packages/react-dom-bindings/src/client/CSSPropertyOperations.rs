/*
 * Operations for dealing with CSS properties.
 */

/**
 * This creates a string that is expected to be equivalent to the style
 * attribute generated by server-side rendering. It by-passes warnings and
 * security checks so it's not safe to use this value for anything other than
 * comparison. It is only used in DEV for SSR validation.
 */
pub fn create_dangerous_string_for_styles(styles: Option<&Unknown>) -> Option<String> {
    if __DEV__ {
        let mut serialized = String::new();
        let mut delimiter = "";
        if let Some(styles) = styles {
            for style_name in js::keys_in(styles) {
                if !styles.has_own_property(&style_name) {
                    continue;
                }
                let value = js::get(styles, &style_name);
                if value.is_some()
                    && !matches!(js::classify(value), Kind::Bool(_))
                    && !js::strict_equals(value, "")
                {
                    let is_custom_property = js::string::index_of(&style_name, "--", None) == 0.0;
                    if is_custom_property {
                        if __DEV__ {
                            check_css_property_string_coercion(value, &style_name);
                        }
                        serialized += &(delimiter.to_owned()
                            + &style_name
                            + ":"
                            + &js::string::trim(&js::concat_text(value).unwrap()));
                    } else if let Kind::Number(number) = js::classify(value)
                        && number != 0.0
                        && !is_unitless_number(&style_name)
                    {
                        serialized += &(delimiter.to_owned()
                            + &hyphenate_style_name(&style_name)
                            + ":"
                            + &js::concat_text(number)
                            + "px");
                    } else {
                        if __DEV__ {
                            check_css_property_string_coercion(value, &style_name);
                        }
                        serialized += &(delimiter.to_owned()
                            + &hyphenate_style_name(&style_name)
                            + ":"
                            + &js::string::trim(&js::concat_text(value).unwrap()));
                    }
                    delimiter = ";";
                }
            }
        }
        return if serialized.is_empty() {
            js::null()
        } else {
            Some(serialized)
        };
    }
    None
}

fn set_value_for_style(style: &CSSStyleProperties, style_name: &str, value: Option<&Unknown>) {
    let is_custom_property = js::string::index_of(style_name, "--", None) == 0.0;
    if __DEV__ && !is_custom_property {
        warn_valid_style(style_name, value);
    }

    if value.is_none()
        || matches!(js::classify(value), Kind::Bool(_))
        || js::strict_equals(value, "")
    {
        if is_custom_property {
            style.set_property(style_name, "", None);
        } else if style_name == "float" {
            style.set_css_float("");
        } else {
            js::set(style, style_name, "");
        }
    } else if is_custom_property {
        style.set_property(style_name, unsafe { js::cast(value) }, None);
    } else if let Kind::Number(number) = js::classify(value)
        && number != 0.0
        && !is_unitless_number(style_name)
    {
        js::set(style, style_name, js::concat_text(number) + "px"); // Presumes implicit 'px' suffix for unitless numbers
    } else if style_name == "float" {
        style.set_css_float(unsafe { js::cast(value) });
    } else {
        if __DEV__ {
            check_css_property_string_coercion(value, style_name);
        }
        js::set(
            style,
            style_name,
            js::string::trim(&js::concat_text(value).unwrap()),
        );
    }
}

/**
 * Sets the value for multiple styles on a node.  If a value is specified as
 * '' (empty string), the corresponding style property will be unset.
 *
 * @param {DOMElement} node
 * @param {object} styles
 */
pub fn set_value_for_styles(
    node: &Element,
    styles: Option<&'static Unknown>,
    prev_styles: Option<&'static Unknown>,
) {
    if styles.is_some()
        && !matches!(
            js::classify(styles),
            Kind::Object(_) | Kind::Array(_) | Kind::Null
        )
    {
        panic!(
            "{}",
            concat!(
                "The `style` prop expects a mapping from style properties to values, ",
                "not a string. For example, style={{marginRight: spacing + 'em'}} when ",
                "using JSX."
            )
        );
    }
    if __DEV__ && let Some(styles) = styles.filter(|styles| js::truthy(Some(*styles))) {
        // Freeze the next style object so that we can assume it won't be
        // mutated. We have already warned for this in the past.
        js::object::freeze(styles);
    }

    let style: &CSSStyleProperties = unsafe { js::cast(js::get(node, "style")) };

    if let Some(prev_styles) = prev_styles {
        if __DEV__ {
            validate_shorthand_property_collision_in_dev(prev_styles, styles);
        }

        for style_name in js::keys_in(prev_styles) {
            if prev_styles.has_own_property(&style_name)
                && styles.is_none_or(|styles| !styles.has_own_property(&style_name))
            {
                // Clear style
                let is_custom_property = js::string::index_of(&style_name, "--", None) == 0.0;
                if is_custom_property {
                    style.set_property(&style_name, "", None);
                } else if style_name == "float" {
                    style.set_css_float("");
                } else {
                    js::set(style, &style_name, "");
                }
                track_host_mutation();
            }
        }
        if let Some(styles) = styles {
            for style_name in js::keys_in(styles) {
                let value = js::get(styles, &style_name);
                if styles.has_own_property(&style_name)
                    && !js::strict_equals(js::get(prev_styles, &style_name), value)
                {
                    set_value_for_style(style, &style_name, value);
                    track_host_mutation();
                }
            }
        }
    } else if let Some(styles) = styles {
        for style_name in js::keys_in(styles) {
            if styles.has_own_property(&style_name) {
                let value = js::get(styles, &style_name);
                set_value_for_style(style, &style_name, value);
            }
        }
    }
}

fn is_value_empty(value: Option<&Unknown>) -> bool {
    value.is_none() || matches!(js::classify(value), Kind::Bool(_)) || js::strict_equals(value, "")
}

/**
 * Given {color: 'red', overflow: 'hidden'} returns {
 *   color: 'color',
 *   overflowX: 'overflow',
 *   overflowY: 'overflow',
 * }. This can be read as "the overflowY property was set by the overflow
 * shorthand". That is, the values are the property that each was derived from.
 */
fn expand_shorthand_map(styles: &Unknown) -> &'static Dict<String> {
    let expanded = dict::new();
    for key in js::keys_in(styles) {
        let longhands = SHORTHAND_TO_LONGHAND
            .with(|shorthand_to_longhand| dict::get(shorthand_to_longhand, &key).copied());
        for longhand in longhands.unwrap_or(&[key.as_str()]) {
            dict::set(expanded, longhand, key.clone());
        }
    }
    expanded
}

/**
 * When mixing shorthand and longhand property names, we warn during updates if
 * we expect an incorrect result to occur. In particular, we warn for:
 *
 * Updating a shorthand property (longhand gets overwritten):
 *   {font: 'foo', fontVariant: 'bar'} -> {font: 'baz', fontVariant: 'bar'}
 *   becomes .style.font = 'baz'
 * Removing a shorthand property (longhand gets lost too):
 *   {font: 'foo', fontVariant: 'bar'} -> {fontVariant: 'bar'}
 *   becomes .style.font = ''
 * Removing a longhand property (should revert to shorthand; doesn't):
 *   {font: 'foo', fontVariant: 'bar'} -> {font: 'foo'}
 *   becomes .style.fontVariant = ''
 */
fn validate_shorthand_property_collision_in_dev(
    prev_styles: &Unknown,
    next_styles: Option<&Unknown>,
) {
    if __DEV__ {
        let Some(next_styles) = next_styles.filter(|next_styles| js::truthy(Some(*next_styles)))
        else {
            return;
        };

        // Compute the diff as it would happen elsewhere.
        let expanded_updates: &Dict<String> = dict::new();
        if js::truthy(Some(prev_styles)) {
            for key in js::keys_in(prev_styles) {
                if prev_styles.has_own_property(&key) && !next_styles.has_own_property(&key) {
                    let longhands = SHORTHAND_TO_LONGHAND.with(|shorthand_to_longhand| {
                        dict::get(shorthand_to_longhand, &key).copied()
                    });
                    for longhand in longhands.unwrap_or(&[key.as_str()]) {
                        dict::set(expanded_updates, longhand, key.clone());
                    }
                }
            }
        }
        for key in js::keys_in(next_styles) {
            if next_styles.has_own_property(&key)
                && (!js::truthy(Some(prev_styles))
                    || !js::strict_equals(js::get(prev_styles, &key), js::get(next_styles, &key)))
            {
                let longhands = SHORTHAND_TO_LONGHAND
                    .with(|shorthand_to_longhand| dict::get(shorthand_to_longhand, &key).copied());
                for longhand in longhands.unwrap_or(&[key.as_str()]) {
                    dict::set(expanded_updates, longhand, key.clone());
                }
            }
        }

        let expanded_styles = expand_shorthand_map(next_styles);
        let warned_about: &Dict<bool> = dict::new();
        for key in js::keys_in(js::unknown(expanded_updates)) {
            let original_key = dict::get(expanded_updates, &key)
                .cloned()
                .unwrap_or_default();
            let correct_original_key = dict::get(expanded_styles, &key);
            if let Some(correct_original_key) = correct_original_key
                && !correct_original_key.is_empty()
                && original_key != *correct_original_key
            {
                let warning_key = original_key.clone() + "," + correct_original_key;
                if dict::get(warned_about, &warning_key).is_some_and(|&warned| warned) {
                    continue;
                }
                dict::set(warned_about, &warning_key, true);
                console::error((
                    concat!(
                        "%s a style property during rerender (%s) when a ",
                        "conflicting property is set (%s) can lead to styling bugs. To ",
                        "avoid this, don't mix shorthand and non-shorthand properties ",
                        "for the same value; instead, replace the shorthand with ",
                        "separate values."
                    ),
                    if is_value_empty(js::get(next_styles, &original_key)) {
                        "Removing"
                    } else {
                        "Updating"
                    },
                    original_key,
                    correct_original_key,
                ));
            }
        }
    }
}
